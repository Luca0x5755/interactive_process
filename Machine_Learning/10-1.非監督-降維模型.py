# 6. 結論與比較
# =============================================================================
"""
本次教學我們實作了三種核心的降維技術，並將它們應用於手寫數字資料集的視覺化。

**總結比較**：
- **PCA**：
  - **類型**：線性
  - **優點**：速度快、可解釋性強、確定性。
  - **缺點**：無法捕捉非線性結構。
  - **適用**：快速初步探索、去除線性相關特徵、作為其他模型的前處理。

- **t-SNE**：
  - **類型**：非線性
  - **優點**：極佳的局部結構保留能力，能產生非常清晰的群集視覺化效果。
  - **缺點**：計算慢、結果隨機、群集間距離無意義。
  - **適用**：純粹的資料視覺化與探索，不建議用於模型前處理。

- **UMAP**：
  - **類型**：非線性
  - **優點**：速度快、在局部與全域結構之間取得良好平衡。
  - **缺點**：結果也具隨機性，參數選擇對結果影響大。
  - **適用**：高效能的視覺化、可作為模型前處理、處理大規模資料。

**選擇策略**：
- 想快速查看資料大概長相，或需要為模型做前處理 -> **PCA**
- 專注於產生最清晰的群集視覺化效果，且資料量不大 -> **t-SNE**
- 需要高效能、可擴展的視覺化，並希望保留更多全域結構 -> **UMAP**

降維是機器學習中一項強大而實用的工具，掌握它能讓你更深入地理解資料，並建立
更高效能的模型。
"""
