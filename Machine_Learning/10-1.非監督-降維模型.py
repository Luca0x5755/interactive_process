# =============================================================================
# 1. 主題介紹：什麼是降維 (Dimensionality Reduction)？
# =============================================================================
"""
在機器學習中，我們處理的資料集可能包含數十、數百甚至數千個特徵（維度）。
雖然更多的特徵可能意味著更多的資訊，但高維度資料也帶來了許多挑戰，統稱為
「維度災難」(Curse of Dimensionality)。

**高維度的問題：**
1.  **計算成本高**：特徵越多，模型訓練所需的時間與運算資源就越多。
2.  **資料稀疏性**：在高維空間中，資料點之間的距離變得非常大，樣本分佈變得稀疏，
    使得尋找規律變得更加困難。
3.  **過擬合風險**：過多的特徵可能包含雜訊或不相關的資訊，導致模型學習到這些雜訊
    而非真實的規律，造成過擬合。
4.  **難以視覺化**：人類只能直觀地理解二維或三維空間，無法直接觀察高維度資料的
    分佈與結構。

**降維的核心目的**，就是在盡可能保留原始資料結構與資訊的前提下，減少特徵的
數量。它扮演著「資料壓縮」與「特徵提取」的角色，將原始的高維特徵轉換為一組
新的、更少數量的低維特徵。

**降維的重要性：**
- **提升模型效能與效率**：減少計算負擔，降低過擬合風險。
- **資料視覺化**：將資料投影到二維或三維空間，讓我們能直觀地觀察資料的群集、
  流形結構或異常點，是探索性資料分析 (EDA) 的關鍵一環。
"""

print("\n" + "="*70)
print("第一部分：主題介紹 - 降維的重要性")
print("="*70)


# =============================================================================
# 2. 準備資料：手寫數字資料集
# =============================================================================
# 本次教學我們將使用 scikit-learn 內建的「手寫數字資料集」(Digits Dataset)。
# 這個資料集的每個樣本是一張 8x8 像素的灰階圖片，代表一個手寫數字 (0-9)。
# 每張圖片可以被攤平成一個 64 維的向量（8*8=64），我們的目標就是將這個
# 64 維的資料降低到 2 維，並在圖表上觀察降維後的效果。

# 載入資料
digits = load_digits()
X = digits.data  # 特徵矩陣 (1797 筆資料, 64 個特徵)
y = digits.target  # 目標標籤 (0-9 的數字)

print(f"資料集讀取成功！")
print(f"特徵矩陣 (X) 的形狀：{X.shape}")
print(f"目標標籤 (y) 的形狀：{y.shape}")

# --- 資料標準化 ---
# 許多降維演算法（特別是 PCA）對特徵的尺度非常敏感。如果特徵的變異數差異很大，
# 變異數較大的特徵會主導降維的結果。因此，在進行降維前，將所有特徵標準化是
# 一個非常重要的步驟。
# 標準化：將數據轉換為平均值為 0，標準差為 1 的分佈。
scaler = StandardScaler()
X_scaled = scaler.fit_transform(X)

print("\n資料已完成標準化，所有特徵現在具有相同的尺度。")


# =============================================================================
# 3. 降維技術一：主成分分析 (Principal Component Analysis, PCA)
# =============================================================================
"""
PCA 是最廣為人知且最常用的線性降維技術。

**核心思想**：
PCA 旨在找到一組新的、互相垂直（正交）的座標軸，稱為「主成分」。
第一個主成分會對齊資料中變異數最大的方向。
第二個主成分會對齊與第一個主成分垂直且變異數次大的方向，以此類推。

它透過線性變換將原始資料投影到新的主成分上，從而達到降維的目的。
PCA 的優點是速度快、可解釋性強（每個主成分都代表了原始特徵的線性組合），
但其假設資料是線性可分的，對於複雜的非線性結構效果可能不佳。
"""
print("\n" + "="*70)
print("第二部分：實作主成分分析 (PCA)")
print("="*70)

# 初始化 PCA 模型，設定目標維度為 2
pca = PCA(n_components=2, random_state=42)

# 擬合並轉換標準化後的資料
X_pca = pca.fit_transform(X_scaled)

print(f"PCA 降維完成！")
print(f"降維後資料的形狀：{X_pca.shape}")
print(f"前兩個主成分解釋的變異數比例：{pca.explained_variance_ratio_}")
print(f"總解釋變異數：{sum(pca.explained_variance_ratio_):.2%}")

# --- 視覺化 PCA 結果 ---
plt.figure(figsize=(10, 8))
sns.scatterplot(
    x=X_pca[:, 0],
    y=X_pca[:, 1],
    hue=y,                # 使用真實標籤來為點著色，以驗證分群效果
    palette=sns.color_palette("hsv", 10), # 使用 10 種不同顏色
    legend="full"
)
plt.title("PCA of Digits Dataset (64D -> 2D)")
plt.xlabel("Principal Component 1")
plt.ylabel("Principal Component 2")
plt.legend(title="Digit")
plt.grid(True)
plt.show()

print("\nPCA 視覺化圖表已生成。可以看到不同數字的群集有部分重疊，但已初步分開。")


# =============================================================================
# 4. 降維技術二：t-SNE (t-Distributed Stochastic Neighbor Embedding)
# =============================================================================
"""
t-SNE 是一種強大的非線性降維技術，特別擅長於高維資料的視覺化。

**核心思想**：
t-SNE 的目標是將高維空間中相似的點（距離近）在低維空間中也保持相似。
它會計算點與點之間的成對相似度，並試圖在低維空間中重現這個相似度分佈。
與 PCA 不同，t-SNE 能捕捉到資料中複雜的、非線性的流形結構。

**注意事項**：
- **計算成本高**：對於大量資料，t-SNE 的計算時間會非常長。
- **結果隨機性**：t-SNE 包含隨機過程，每次執行的結果可能略有不同，設定 `random_state` 可確保結果重現。
- **不保留全域結構**：t-SNE 擅長保留局部結構，但降維後點與點之間的距離（特別是不同群集間的距離）不具有實際意義。它主要用於觀察群集，而非度量距離。
"""
print("\n" + "="*70)
print("第三部分：實作 t-SNE")
print("="*70)

# 初始化 t-SNE 模型
# perplexity: 困惑度，與每個點的近鄰數量有關，通常建議值在 5 到 50 之間。
# n_iter: 迭代次數。
tsne = TSNE(n_components=2, perplexity=30, n_iter=1000, random_state=42)

# 擬合並轉換資料（t-SNE 通常直接用在原始或標準化資料上）
X_tsne = tsne.fit_transform(X_scaled)

print(f"t-SNE 降維完成！")
print(f"降維後資料的形狀：{X_tsne.shape}")

# --- 視覺化 t-SNE 結果 ---
plt.figure(figsize=(10, 8))
sns.scatterplot(
    x=X_tsne[:, 0],
    y=X_tsne[:, 1],
    hue=y,
    palette=sns.color_palette("hsv", 10),
    legend="full"
)
plt.title("t-SNE of Digits Dataset (64D -> 2D)")
plt.xlabel("t-SNE Dimension 1")
plt.ylabel("t-SNE Dimension 2")
plt.legend(title="Digit")
plt.grid(True)
plt.show()

print("\nt-SNE 視覺化圖表已生成。與 PCA 相比，各個數字的群集被分得更開，邊界更清晰。")


# =============================================================================
# 5. 降維技術三：UMAP (Uniform Manifold Approximation and Projection)
# =============================================================================
"""
UMAP 是近年來非常流行的一種新型非線性降維演算法，常被視為 t-SNE 的改良版。

**核心思想**：
UMAP 同樣致力於尋找資料的低維流形結構，但其數學基礎源於拓撲學。
它在保留局部結構的同時，通常能比 t-SNE 更好地保留資料的全域結構。

**優點**：
- **速度極快**：UMAP 的計算效率遠高於 t-SNE，能處理更大規模的資料集。
- **更好的全域結構保留**：降維後的群集間距更能反映原始空間的關係。
- **應用更廣**：除了視覺化，UMAP 也可以作為機器學習模型的預處理步驟。
"""
if umap:
    print("\n" + "="*70)
    print("第四部分：實作 UMAP")
    print("="*70)

    # 初始化 UMAP 模型
    # n_neighbors: 控制局部與全域結構平衡的關鍵參數。值越小，越關注局部細節；值越大，越關注全域結構。
    # min_dist: 控制嵌入點的緊密程度。值越小，群集越緊湊。
    umap_reducer = umap.UMAP(n_neighbors=15, min_dist=0.1, n_components=2, random_state=42)

    # 擬合並轉換資料
    X_umap = umap_reducer.fit_transform(X_scaled)

    print(f"UMAP 降維完成！")
    print(f"降維後資料的形狀：{X_umap.shape}")

    # --- 視覺化 UMAP 結果 ---
    plt.figure(figsize=(10, 8))
    sns.scatterplot(
        x=X_umap[:, 0],
        y=X_umap[:, 1],
        hue=y,
        palette=sns.color_palette("hsv", 10),
        legend="full"
    )
    plt.title("UMAP of Digits Dataset (64D -> 2D)")
    plt.xlabel("UMAP Dimension 1")
    plt.ylabel("UMAP Dimension 2")
    plt.legend(title="Digit")
    plt.grid(True)
    plt.show()

    print("\nUMAP 視覺化圖表已生成。其效果與 t-SNE 類似，但通常計算速度更快。")
else:
    print("\nUMAP 部分已跳過，因為 `umap-learn` 套件未安裝。")


