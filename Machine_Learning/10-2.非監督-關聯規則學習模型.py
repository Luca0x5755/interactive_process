# =============================================================================
# 0. 導入必要套件
# =============================================================================
# 導入 pandas 進行資料處理，並從 mlxtend 函式庫導入所需模組
import pandas as pd
from mlxtend.preprocessing import TransactionEncoder
from mlxtend.frequent_patterns import apriori, association_rules

print("套件導入成功！準備開始學習關聯規則。")


# =============================================================================
# 1. 主題介紹：什麼是關聯規則學習 (Association Rule Learning)？
# =============================================================================
"""
關聯規則學習是一種在大型資料集中，探索變數之間「有趣關聯」的非監督式學習方法。
它最經典的應用場景就是「市場籃分析」(Market Basket Analysis)。

**核心價值：**
關聯規則的價值在於揭示那些看似無關，但實際上卻經常一同出現的項目組合。
最著名的例子就是「尿布與啤酒」的故事：分析超市的交易數據發現，購買尿布的
男性顧客，有很高的機率會同時購買啤酒。這個發現，讓超市可以將這兩樣商品
擺放在相近的位置，從而提升銷售額。

**關鍵術語：**
- **項目集 (Itemset):** 一個或多個項目構成的集合，例如 {牛奶, 麵包}。
- **支持度 (Support):** 一個項目集在所有交易中出現的頻率。
  Support({A, B}) = (包含A和B的交易數) / (總交易數)
- **信賴度 (Confidence):** 當交易中包含項目集A時，同時也包含項目集B的條件機率。
  Confidence(A -> B) = Support({A, B}) / (Support({A}))
- **提升度 (Lift):** 衡量規則「A -> B」相較於「A和B獨立發生」時，提升了多少。
  Lift(A -> B) = Support({A, B}) / (Support({A}) * Support({B}))
  - Lift > 1: A和B存在正相關 (購買A會提升購買B的機率)。
  - Lift = 1: A和B相互獨立。
  - Lift < 1: A和B存在負相關 (購買A會降低購買B的機率)。
"""

print("\n" + "="*60)
print("第一部分：主題介紹 - 關聯規則學習")
print("="*60)


# =============================================================================
# 2. 資料準備 (Data Preparation)
# =============================================================================
# 關聯規則演算法 (如 Apriori) 需要特定的輸入格式：一個 one-hot 編碼的 DataFrame。
# 在這個 DataFrame 中，每一列代表一筆交易，每一行代表一個商品，
#儲存格中的值為 True/False (或 1/0)，表示該交易是否包含該商品。

# 步驟 2.1: 創建模擬交易資料
# 假設我們有以下幾筆超市的交易紀錄
# 每一筆 list 代表一位顧客一次購買的所有商品
dataset = [['牛奶', '洋蔥', '肉豆蔻', '芸豆', '雞蛋', '優格'],
           ['蒔蘿', '洋蔥', '肉豆蔻', '芸豆', '雞蛋', '優格'],
           ['牛奶', '蘋果', '芸豆', '雞蛋'],
           ['牛奶', '獨角獸', '玉米', '芸豆', '優格'],
           ['玉米', '洋蔥', '洋蔥', '芸豆', '冰淇淋', '雞蛋']]

print("\n" + "="*60)
print("第二部分：資料準備")
print("="*60)
print("原始交易資料 (List of Lists):")
print(dataset)

# 步驟 2.2: 轉換資料格式
# 我們使用 mlxtend 的 TransactionEncoder 來將資料轉換為 one-hot 編碼格式
te = TransactionEncoder()
te_ary = te.fit(dataset).transform(dataset)
df = pd.DataFrame(te_ary, columns=te.columns_)

print("\n轉換為 One-Hot 編碼的 DataFrame:")
print(df)


# =============================================================================
# 3. 實作範例：找出頻繁項目集與生成規則
# =============================================================================
# 現在我們的資料已經準備好了，可以開始進行分析。

# 步驟 3.1: 使用 Apriori 演算法找出頻繁項目集
# Apriori 演算法是關聯規則中最經典的演算法，用於找出所有滿足「最小支持度」
# (min_support) 門檻的項目集。
# `min_support=0.6` 意味著我們只關心在至少 60% 的交易中都出現過的項目集。
# `use_colnames=True` 讓輸出的項目集直接顯示商品名稱，而不是欄位索引。

print("\n" + "="*60)
print("第三部分：Apriori 演算法與規則生成")
print("="*60)

frequent_itemsets = apriori(df, min_support=0.6, use_colnames=True)

print("\n步驟 3.1: 找出頻繁項目集 (min_support=0.6)")
print("-------------------------------------------")
print("支持度 (Support) 代表該項目集在所有交易中的出現比例。")
print(frequent_itemsets)


# 步驟 3.2: 從頻繁項目集中生成關聯規則
# 找到頻繁項目集後，下一步就是從中生成關聯規則。
# 我們可以設定不同的評估指標 (metric) 與其門檻 (min_threshold)。
# 常見的指標是 'confidence' 或 'lift'。
# `metric='confidence', min_threshold=0.7` 表示我們只關心
# 信賴度至少為 70% (0.7) 的規則。

association_rules_df = association_rules(frequent_itemsets, metric="confidence", min_threshold=0.7)

print("\n步驟 3.2: 生成關聯規則 (min_confidence=0.7)")
print("---------------------------------------------")
print("信賴度 (Confidence) 指的是，當顧客購買了前項(antecedents)，有多高的機率會購買後項(consequents)。")
print("提升度 (Lift) 指的是，購買前項對於提升後項購買率的程度，大於1表示有正向幫助。")
# 為了方便閱讀，我們可以篩選並排序結果
# 例如，找出提升度 (lift) > 1.2 的規則，並以降序排列
filtered_rules = association_rules_df[association_rules_df['lift'] > 1.2].sort_values(by='lift', ascending=False)

print("\n篩選並排序後的規則 (lift > 1.2):")
print(filtered_rules)


# =============================================================================
# 4. 結果解讀與分析
# =============================================================================
"""
讓我們來解讀一條規則，例如表格中的第一條：
{洋蔥, 雞蛋} -> {芸豆}

- antecedents (前項): {'洋蔥', '雞蛋'}
- consequents (後項): {'芸豆'}
- antecedent support: 購買 {洋蔥, 雞蛋} 的交易佔總交易的 60%。
- consequent support: 購買 {芸豆} 的交易佔總交易的 100%。
- support: 同時購買 {洋蔥, 雞蛋, 芸豆} 的交易佔總交易的 60%。
- confidence: 在所有購買了 {洋蔥, 雞蛋} 的交易中，有 100% 的交易也購買了 {芸豆}。
             這是一個非常強的信號！
- lift: 1.0。這表示購買 {洋蔥, 雞蛋} 並沒有特別「提升」購買 {芸豆} 的機率，
        因為 {芸豆} 本身在所有交易中都出現了 (支持度為1.0)，所以 lift 等於 1。

再看另一條規則：
{洋蔥} -> {雞蛋}

- confidence: 1.0。表示買了洋蔥的顧客，100%會買雞蛋。
- lift: 1.25。表示「購買洋蔥」這件事，讓「購買雞蛋」的機率提升了 25%。
        這就是一個非常有價值的發現！店家可以考慮將洋蔥和雞蛋做捆綁促銷。

透過分析這些規則，企業可以制定更精準的行銷策略、改善商品陳列、設計推薦系統等，
從而創造更多商業價值。
"""
