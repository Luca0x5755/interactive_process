# 4. 總結與選擇建議
# =============================================================================
"""
我們已經成功實作了三種主流的非監督式異常偵測演算法。從視覺化結果可以看出，
三種模型都能有效地識別出我們刻意製造的離群點，但它們的決策邊界和側重點
略有不同。

**如何選擇合適的模型？**

- **隔離森林 (Isolation Forest)**:
  - **優點**: 計算效率高，對高維數據表現良好，通常是異常偵測的首選基準模型。
  - **缺點**: 對於資料分布非常密集的群集，可能會將一些邊緣的正常點誤判為異常。
  - **適用場景**: 大數據集、高維度特徵、需要快速得到結果的場景。

- **局部異常因子 (LOF)**:
  - **優點**: 能夠處理不同密度的資料群集，對局部異常的偵測非常敏感。
  - **缺點**: 計算複雜度較高，在非常大的資料集上可能運行緩慢。
  - **適用場景**: 資料包含多個密度不均的群集，且需要精準識別局部異常點時。

- **單類支持向量機 (One-Class SVM)**:
  - **優點**: 能夠學習複雜的非線性邊界，對資料分佈的假設較少。
  - **缺點**: 對超參數 (特別是 `gamma` 和 `nu`) 的選擇非常敏感，需要仔細調校。
  - **適用場景**: 當正常資料的邊界呈現複雜、非球形的結構時。

**最終建議**：在實務中，沒有一體適用的最佳演算法。建議可以從計算成本較低的
隔離森林開始，並根據資料的特性與業務需求，嘗試使用 LOF 或 One-Class SVM
進行比較，甚至可以整合多個模型的結果來做出更穩健的判斷。
"""

