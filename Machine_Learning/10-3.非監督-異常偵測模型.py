# =============================================================================
# 1. 主題介紹：什麼是異常偵測 (Anomaly Detection)？
# =============================================================================
"""
**異常偵測 (Anomaly Detection)**，又稱為離群點偵測 (Outlier Detection)，其核心
目標是從一個資料集中，識別出那些與「絕大多數」資料點行為模式顯著不同的觀測值。
這些被識別出來的特殊資料點，就被稱為「異常」或「離群點」。

**為何異常偵測如此重要？**
在許多領域，這些罕見的異常點往往蘊含著最有價值的資訊，例如：
- **金融領域**：偵測信用卡盜刷、洗錢等非法交易行為。
- **網路安全**：識別駭客入侵、惡意軟體攻擊等網路流量異常。
- **工業製造**：預測設備故障，實現預防性維護，避免產線中斷。
- **醫療健康**：從生理監測數據中發現預示疾病的早期徵兆。

**為何使用「非監督式」方法？**
在真實世界中，異常事件通常非常稀少，且樣態多變，導致我們難以取得足夠
且標記完整的「異常樣本」來訓練一個監督式分類模型。非監督式方法的最大
優勢在於，它**不需要**事先標記好的資料。它僅僅基於資料自身的結構、分佈
與密度，去學習出一個「正常」的輪廓，並將所有不符合這個輪廓的點視為異常。
"""

print("\n" + "="*70)
print("第一部分：主題介紹 - 異常偵測的重要性與非監督式方法的應用")
print("="*70)


# =============================================================================
# 2. 準備模擬資料
# =============================================================================
# 為了清楚地展示各演算法的效果，我們將手動生成一些資料。
# 主體資料是兩群集中的「正常」點，另外我們再隨機生成一些遠離中心的「異常」點。

# 設定隨機種子以確保每次執行的結果一致
np.random.seed(42)

# 生成 200 個正常的資料點，分為兩群
X_normal, _ = make_blobs(n_samples=200, centers=2, cluster_std=1.0, random_state=42)

# 生成 20 個均勻分佈的異常點
X_outliers = np.random.uniform(low=-8, high=8, size=(20, 2))

# 將正常與異常資料合併成最終的資料集
X = np.vstack([X_normal, X_outliers])

# 建立一個標籤陣列，方便後續視覺化時區分真實的正常點與異常點
# 1 代表正常 (inlier), -1 代表異常 (outlier)
y_true = np.array([1] * 200 + [-1] * 20)

print("\n✅ 模擬資料生成完畢！")
print(f"資料集維度: {X.shape}")
print(f"其中包含 {len(X_normal)} 個正常點與 {len(X_outliers)} 個異常點。")

# 視覺化我們生成的資料
plt.figure(figsize=(8, 6))
plt.scatter(X_normal[:, 0], X_normal[:, 1], c='lightblue', label='正常資料 (Inliers)')
plt.scatter(X_outliers[:, 0], X_outliers[:, 1], c='red', marker='x', label='真實異常 (Outliers)')
plt.title('模擬生成的資料集')
plt.xlabel('特徵 1')
plt.ylabel('特徵 2')
plt.legend()
plt.grid(True, linestyle='--', alpha=0.6)
plt.show()


# =============================================================================
# 3. 核心演算法實作與解析
# =============================================================================
"""
接下來，我們將逐一介紹三種強大的非監督式異常偵測演算法，並在我們的模擬
資料上進行實作。

為了方便比較，我們先定義一個視覺化函式，它能將各模型的偵測結果繪製出來。
"""

def plot_anomaly_detection(model, X, y_true, model_name):
    """
    視覺化異常偵測結果的輔助函式。

    參數:
    model: 已訓練好的異常偵測模型。
    X: 輸入的特徵資料。
    y_true: 真實的標籤 (用於比較)。
    model_name: 模型的名稱 (用於圖表標題)。
    """
    # 讓模型進行預測
    # scikit-learn 中的異常偵測模型會將正常點預測為 1，異常點預測為 -1
    y_pred = model.fit_predict(X)

    # 計算偵測到的異常點數量
    n_errors = (y_pred != y_true).sum()

    plt.figure(figsize=(10, 8))

    # 繪製模型預測的結果
    # 預測為異常的點 (y_pred == -1)
    plt.scatter(X[y_pred == -1, 0], X[y_pred == -1, 1],
                c='red', marker='x', s=100, label='預測為異常')
    # 預測為正常的點 (y_pred == 1)
    plt.scatter(X[y_pred == 1, 0], X[y_pred == 1, 1],
                c='lightblue', marker='o', s=50, label='預測為正常')

    # 如果模型有決策邊界函式 (如 One-Class SVM)，則繪製出來
    if hasattr(model, "decision_function"):
        Z = model.decision_function(np.c_[xx.ravel(), yy.ravel()])
        Z = Z.reshape(xx.shape)
        plt.contour(xx, yy, Z, levels=[0], linewidths=2, colors='black')

    plt.title(f'{model_name}\n(偵測錯誤數量: {n_errors}/{len(X)})', fontsize=16)
    plt.xlabel('特徵 1', fontsize=12)
    plt.ylabel('特徵 2', fontsize=12)
    plt.legend()
    plt.grid(True, linestyle='--', alpha=0.6)
    plt.show()

# 為了繪製決策邊界，我們先建立一個網格
xx, yy = np.meshgrid(np.linspace(-10, 10, 500), np.linspace(-10, 10, 500))

print("\n" + "="*70)
print("第三部分：核心演算法實作")
print("="*70)

# -----------------------------------------------------------------------------
# 3.1 隔離森林 (Isolation Forest)
# -----------------------------------------------------------------------------
"""
**核心思想**：異常點通常比正常點更容易被「孤立」。

隔離森林的運作方式類似於隨機森林。它會建立多棵決策樹，但每棵樹的目的不是
為了分類，而是為了「隔離」每一個資料點。在建樹的過程中，演算法會隨機選擇
一個特徵，然後在該特徵的最大值與最小值之間隨機選擇一個分割點。

由於異常點通常遠離資料密集區，它們平均只需要很少的幾次分割就能被完全獨立
出來（即從根節點到葉節點的路徑很短）。相反，正常點因為處在資料密集區，需要
經過很多次分割才能被隔離。模型最終會計算每個點的平均路徑長度，路徑越短，
該點被判定為異常的可能性就越高。

**主要參數**：
- `n_estimators`: 建立的決策樹數量。
- `contamination`: 資料集中異常點的比例預估值。這是一個超參數，需要根據
  領域知識或經驗來設定。'auto' 會使用原始論文中的預設值。
- `random_state`: 隨機種子，確保結果可重現。
"""
print("\n--- 3.1 隔離森林 (Isolation Forest) ---")

# 初始化模型
# 我們假設資料中約有 10% 的異常點 (20 / 220 ≈ 0.09)
iso_forest = IsolationForest(n_estimators=100, contamination=0.1, random_state=42)

# 視覺化結果
plot_anomaly_detection(iso_forest, X, y_true, 'Isolation Forest')
print("隔離森林模型執行完畢。")


# -----------------------------------------------------------------------------
# 3.2 局部異常因子 (Local Outlier Factor, LOF)
# -----------------------------------------------------------------------------
"""
**核心思想**：異常點的「局部密度」會顯著低於其鄰近點。

LOF 是一個基於密度的演算法。它不會為整個資料集建立一個全域的「正常」標準，
而是關注每個點的「局部」鄰域。對於一個資料點 p，LOF 會比較 p 的密度與其
鄰居們的密度。

- 如果點 p 的密度遠低於其鄰居（意味著 p 處在一個稀疏的區域，而它的鄰居們
  處在一個密集的區域），那麼 p 就會被判定為一個異常點。
- 如果點 p 的密度與其鄰居們相似，它就是一個正常點。

這種局部性的考量使得 LOF 對於不同密度的資料群集都能有很好的效果。

**主要參數**：
- `n_neighbors`: 計算局部密度時所考慮的鄰居數量。
- `contamination`: 資料集中異常點的比例預估值。
"""
print("\n--- 3.2 局部異常因子 (Local Outlier Factor, LOF) ---")

# 初始化模型
# novelty=True 表示我們將用它來偵測新資料是否為異常
lof = LocalOutlierFactor(n_neighbors=20, contamination=0.1, novelty=True)

# 視覺化結果
plot_anomaly_detection(lof, X, y_true, 'Local Outlier Factor (LOF)')
print("局部異常因子模型執行完畢。")


# -----------------------------------------------------------------------------
# 3.3 單類支持向量機 (One-Class SVM)
# -----------------------------------------------------------------------------
"""
**核心思想**：學習一個能包圍住「大多數」正常資料的邊界。

One-Class SVM 是傳統 SVM 的一個變種。傳統 SVM 的目標是找到一個能「區分」
兩類資料的超平面，而 One-Class SVM 的目標是找到一個能「包圍」單一類別資料
（即正常資料）的超平面（或在高維空間中的超球面）。

所有落在這個邊界之外的點，都會被視為異常。

**主要參數**：
- `kernel`: 核函數，用於將資料映射到更高維的空間，以便找到非線性的邊界。
  'rbf' (徑向基函數) 是最常用的選擇。
- `gamma`: 'rbf' 核函數的係數，影響單個訓練樣本的影響範圍。
- `nu`: 一個介於 0 和 1 之間的超參數，它同時代表了「訓練錯誤的上限」和
  「支持向量的下限」的比例。可以直觀地理解為預期的異常點比例。
"""
print("\n--- 3.3 單類支持向量機 (One-Class SVM) ---")

# 初始化模型
# nu 的值也設為我們預估的異常比例
one_class_svm = OneClassSVM(kernel='rbf', gamma='auto', nu=0.1)

# 視覺化結果
plot_anomaly_detection(one_class_svm, X, y_true, 'One-Class SVM')
print("單類支持向量機模型執行完畢。")


